# %% 셀 28
actual = 0.1 + 0.2
expected = 0.3
print("계산값:", repr(actual))
print("직접 동등 비교:", actual == expected)
print("허용오차 비교:", np.isclose(actual, expected, rtol=0, atol=1e-12))
